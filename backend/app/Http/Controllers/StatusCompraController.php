    public function showByNivel(Request $request)
    {

        $token = $request->header('Authorization');

        if (!$token) {
            return response()->json(['error' => 'Token não fornecido'], 401);
        }

        $user = auth('api')->user();

        $status = StatusCompraModel::where('visivel', "=", $user->compra)->get();

        return Response()->json($status, 200);
    }
